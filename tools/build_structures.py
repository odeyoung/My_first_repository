"""Draws every structure in questions.js to SVG and writes structures.js.
Run after editing questions:  node tools/dump_smiles.js | python3 tools/build_structures.py
Needs: pip install rdkit"""
import json, re, sys
from rdkit import Chem
from rdkit.Chem.Draw import rdMolDraw2D

TOSYLATE = "OS(=O)(=O)c1ccc(C)cc1"

def svg_for(smiles):
    # A tosylate is drawn as the usual "OTs" shorthand: a placeholder atom carries the label.
    mol = Chem.MolFromSmiles(smiles.replace(TOSYLATE, "[At]"))
    if mol is None:
        raise SystemExit("Bad SMILES: " + smiles)
    for a in mol.GetAtoms():
        if a.GetSymbol() == "At":
            a.SetProp("_displayLabel", "OTs")
            a.SetProp("_displayLabelW", "TsO")
    d = rdMolDraw2D.MolDraw2DSVG(-1, -1)
    o = d.drawOptions()
    o.useBWAtomPalette()
    o.setBackgroundColour((1, 1, 1, 0))
    o.fixedBondLength = 30
    o.bondLineWidth = 1.7
    o.padding = 0.12
    o.minFontSize = 15
    o.maxFontSize = 15
    o.addStereoAnnotation = False
    o.explicitMethyl = sum(1 for a in mol.GetAtoms() if a.GetSymbol() == "C") <= 2
    rdMolDraw2D.PrepareAndDrawMolecule(d, mol)
    d.FinishDrawing()
    s = d.GetDrawingText()
    s = re.sub(r"<\?xml[^>]*\?>", "", s)
    s = re.sub(r"<rect[^>]*>\s*</rect>", "", s)
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    s = s.replace("#000000", "currentColor")
    s = re.sub(r"\s*xmlns:(rdkit|xlink)='[^']*'", "", s)
    s = re.sub(r"\s*xml:space='preserve'", "", s)
    s = re.sub(r"\n+", "", s).strip()
    # Labels can poke past RDKit's tight canvas, so widen the viewBox by a margin.
    m = re.search(r"width='([\d.]+)px' height='([\d.]+)px' viewBox='0 0 ([\d.]+) ([\d.]+)'", s)
    w, h, pad = float(m.group(3)), float(m.group(4)), 9
    s = s.replace(m.group(0), "width='%d' height='%d' viewBox='%d %d %d %d'" % (w + 2 * pad, h + 2 * pad, -pad, -pad, w + 2 * pad, h + 2 * pad))
    s = re.sub(r"\s{2,}", " ", s)
    return s

smiles = json.load(sys.stdin)
out = {s: svg_for(s) for s in smiles}
with open("structures.js", "w") as f:
    f.write("/* Generated by tools/build_structures.py. Do not edit by hand. */\nconst STRUCT = ")
    json.dump(out, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print(len(out), "structures", sum(len(v) for v in out.values()) // 1024, "KB")
